// Parity fixture generator for the XML byte-decoding half of src/utils/xml-utils.ts
//   src/utils/xml-utils.ts -> xmlutil.DecodeBytes
//
// The expected values come from EXECUTING the real decodeXmlBytes. The corpus is byte-oriented on
// purpose: every case is a raw byte array, so nothing about the expectations depends on how a file
// would have been written to disk.
//
// Usage: bun run server-go/tools/parity/gen_xmlutil_fixtures.mjs

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')

const { decodeXmlBytes } = await import(
  pathToFileURL(join(repoRoot, 'src', 'utils', 'xml-utils.ts')).href
)

// [label, bytes] — the labels are only for the report; the byte arrays are the input.
const cases = [
  ['empty', []],
  ['plain ascii', [0x3c, 0x61, 0x3e]],
  ['utf8 bom stripped', [0xef, 0xbb, 0xbf, 0x3c, 0x61, 0x3e]],
  ['utf8 bom only -> empty', [0xef, 0xbb, 0xbf]],
  ['utf16le bom', [0xff, 0xfe, 0x3c, 0x00, 0x61, 0x00, 0x3e, 0x00]],
  ['utf16be bom', [0xfe, 0xff, 0x00, 0x3c, 0x00, 0x61, 0x00, 0x3e]],
  ['utf16le no bom', [0x3c, 0x00, 0x61, 0x00, 0x3e, 0x00]],
  ['utf16be no bom', [0x00, 0x3c, 0x00, 0x61, 0x00, 0x3e]],
  // ★ the bare-`<` sniff is gated on FOUR bytes, so a 2-byte input falls through to utf-8
  ['bare 3c 00 is below the sniff threshold', [0x3c, 0x00]],
  ['bare 00 3c is below the sniff threshold', [0x00, 0x3c]],
  ['3-byte input cannot sniff utf16', [0x3c, 0x00, 0x61]],
  ['exactly 4 bytes, le', [0x3c, 0x00, 0x61, 0x00]],
  // malformed / truncated inputs
  ['odd-length utf16le', [0xff, 0xfe, 0x3c, 0x00, 0x61]],
  ['odd-length utf16le, stray byte', [0xff, 0xfe, 0xfd]],
  ['lone high surrogate', [0xff, 0xfe, 0x00, 0xd8]],
  ['lone low surrogate', [0xff, 0xfe, 0x00, 0xdc]],
  ['valid surrogate pair', [0xff, 0xfe, 0x3d, 0xd8, 0x00, 0xde]],
  ['invalid utf8 bytes', [0xff, 0xfe, 0xfd]],
  ['truncated utf8 sequence', [0xe4, 0xb8]],
  ['valid utf8 non-ascii', [0xe4, 0xb8, 0xad]],
  ['nul inside utf8', [0x3c, 0x00, 0x3e]],
  // a realistic tiny document in each encoding
  ['utf8 document', Array.from(new TextEncoder().encode('<?xml version="1.0"?><a/>'))],
  [
    'utf16le document',
    (() => {
      const ascii = '<?xml version="1.0"?><a/>'
      const bytes = [0xff, 0xfe]
      for (const ch of ascii) bytes.push(ch.charCodeAt(0), 0x00)
      return bytes
    })(),
  ],
]

const out = []
for (const [label, bytes] of cases) {
  const arr = Array.from(bytes)
  let entry
  try {
    const text = decodeXmlBytes(new Uint8Array(arr))
    entry = { label, bytes: arr, ok: true, text, codePoints: Array.from(text).map(c => c.codePointAt(0)) }
  } catch (error) {
    entry = { label, bytes: arr, ok: false, error: String(error?.message ?? error) }
  }
  out.push(entry)
}

const fixtures = {
  _comment:
    'GENERATED by gen_xmlutil_fixtures.mjs. Expected values come from EXECUTING the real ' +
    'src/utils/xml-utils.ts decodeXmlBytes. Do not edit by hand.',
  cases: out,
}
writeFileSync(join(here, 'xmlutil_fixtures.json'), JSON.stringify(fixtures, null, 2) + '\n', 'utf8')

console.log('wrote xmlutil_fixtures.json')
console.log(`  cases: ${out.length} (${out.filter(c => c.ok).length} decoded)`)
console.log()
console.log('  ★ the two cases a "tidy" implementation gets wrong:')
for (const label of ['bare 3c 00 is below the sniff threshold', 'odd-length utf16le, stray byte']) {
  const c = out.find(x => x.label === label)
  if (c) console.log(`      ${label}: ${JSON.stringify(c.text)} (codes ${JSON.stringify(c.codePoints)})`)
}
