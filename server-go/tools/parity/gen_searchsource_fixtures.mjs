// Parity fixture generator for src/tools/search-source.ts.
//
// ★ WHY THE QUERIES ARE ALL *SMALL* MATCH SETS.
//
// Measured before writing this: search_source invokes ripgrep WITHOUT --sort, so ripgrep emits
// matches in completion order, which depends on worker scheduling. On our own BlBridge C# source
// a query with 357 matches returned a DIFFERENT 120-match subset on all five runs. Above the
// 120-match limit the tool is therefore nondeterministic by construction, and a byte-for-byte
// comparison there would fail for reasons that have nothing to do with the port.
//
// So every query below matches well under the limit, and the nondeterminism is recorded as a
// property of the upstream tool (capability ledger F22) rather than hidden by a green suite.
//
// The parse and render layers are exercised through the tool itself, so the expectations are the
// tool's real output — not a reimplementation of what it is assumed to do.

import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync, statSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')

// ── the corpus (committed, beside this script) ──────────────────────────────
const corpusDir = join(here, 'fixtures', 'ripgrep-corpus')
if (!existsSync(corpusDir)) {
    console.error(`missing corpus at ${corpusDir}`)
    process.exit(2)
}

// Record the corpus so the Go test can confirm it is reading the same files. Paths use
// forward slashes and are relative to the corpus root, matching how the tool normalises.
function walk(dir, prefix = '') {
    const out = []
    for (const entry of readdirSync(dir, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
        const rel = prefix ? `${prefix}/${entry.name}` : entry.name
        if (entry.isDirectory()) out.push(...walk(join(dir, entry.name), rel))
        else out.push(rel)
    }
    return out
}
const corpusFiles = walk(corpusDir)

// ── run the TypeScript tool ─────────────────────────────────────────────────
const sandboxMod = await import(pathToFileURL(join(repoRoot, 'src', 'utils', 'path-sandbox.ts')).href)
const sourceMod = await import(pathToFileURL(join(repoRoot, 'src', 'tools', 'search-source.ts')).href)
const { PathSandbox } = sandboxMod
const { searchSource } = sourceMod

// The sandbox is created around the corpus directory itself. Passing an absolute path is
// allowed by PathSandbox (it resolves it directly), which keeps the fixture independent of
// whatever `root` env.ts computes.
const sandbox = new PathSandbox(corpusDir)

const cases = [
    { query: 'SAFETY_MARKER', caseSensitive: false },
    { query: 'SAFETY_MARKER', caseSensitive: true },
    { query: 'safety_marker', caseSensitive: false }, // case-insensitive should match
    { query: 'safety_marker', caseSensitive: true }, // case-sensitive should find nothing
    { query: 'namespace', caseSensitive: false },
    { query: 'SAFETY_MARKER', caseSensitive: false, filePattern: '*.cs' },
    { query: 'SAFETY_MARKER', caseSensitive: false, filePattern: 'Handler.cs' },
    { query: 'SAFETY_MARKER', caseSensitive: false, filePattern: 'src/Util/*' },
    // A pattern that matches nothing: exit code 1, which must NOT be treated as an error.
    { query: 'NOTHING_MATCHES_THIS_AT_ALL', caseSensitive: false },
    // A regex, to show the query is passed through to ripgrep verbatim.
    { query: 'SAFETY_(MARKER|NOPE)', caseSensitive: false },
    // Non-ASCII term.
    { query: '中文路径测试', caseSensitive: false },
    // A term with a path separator, and one that would need escaping in a shell.
    { query: 'Void\\s+Run', caseSensitive: false },
    { query: 'class (Handler|Reader)', caseSensitive: false },
    { query: 'SAFETY_MARKER 中文路径测试', caseSensitive: false },
]

const results = []
for (const c of cases) {
    let out
    try {
        const res = await searchSource(sandbox, c.query, c.caseSensitive, c.filePattern)
        out = { ok: true, text: res.content[0].text }
    } catch (error) {
        out = { ok: false, error: String(error?.message ?? error) }
    }
    results.push({ ...c, ...out })
}

// A run whose match count is near the limit, to pin `truncated` and `matches_returned`. Kept
// far below 120 so the ORDER is stable — see the header.
const fixtures = {
    _comment:
        'GENERATED by gen_searchsource_fixtures.mjs. Expected values come from EXECUTING ' +
        'src/tools/search-source.ts (and therefore the real ripgrep) against the corpus in ' +
        'fixtures/ripgrep-corpus. Do not edit by hand.',
    generatedFrom: 'src/tools/search-source.ts (imported)',
    ripgrepVersion: await ripgrepVersion(),
    corpusFiles,
    results,
}

writeFileSync(join(here, 'searchsource_fixtures.json'), JSON.stringify(fixtures, null, 2) + '\n', 'utf8')

console.log('wrote searchsource_fixtures.json')
console.log(`  corpus files : ${corpusFiles.length}`)
console.log(`  cases        : ${results.length} (${results.filter((r) => r.ok).length} rendered)`)
console.log(`  ripgrep      : ${fixtures.ripgrepVersion}`)
console.log()
console.log('  ★ a match with a case-sensitive query:')
const cs = results.find((r) => r.query === 'safety_marker' && r.caseSensitive === true)
if (cs?.ok) for (const l of cs.text.split('\n').slice(0, 8)) console.log('      ' + l)
console.log()
console.log('  ★ a no-match query (exit code 1 must not be an error):')
const none = results.find((r) => r.query === 'NOTHING_MATCHES_THIS_AT_ALL')
if (none?.ok) console.log(none.text.split('\n').map((l) => '      ' + l).join('\n'))
else console.log('      ERROR: ' + none?.error)

async function ripgrepVersion() {
    const proc = Bun.spawn(['rg', '--version'], { stdout: 'pipe', stderr: 'pipe' })
    const text = await new Response(proc.stdout).text()
    await proc.exited
    return text.split('\n')[0].trim()
}
