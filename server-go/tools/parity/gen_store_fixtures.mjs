// Parity fixture generator for src/utils/db.ts and src/utils/memory-db.ts.
//
// These are IO-bound, so the approach differs from the pure functions: instead of
// many inputs to one function, the generator builds ONE real SQLite database with
// deliberate edge cases, then records what the TypeScript returns for each probe. The
// Go side opens a copy of the SAME database and must return the same values.
//
// The database is committed by this script so both sides provably read identical bytes.
//
// Edge cases the schema is built to expose:
//   - a VIEW with the same name as a queryable table, to pin `type = 'table'` (the
//     previous Go version used `type IN ('table','view')` and answered true for views)
//   - a table whose extra columns must NOT make HasColumns fail (it is "all present",
//     not "exactly these")
//   - a numeric column and a NULL column read through TextValue, which the TypeScript
//     reports as undefined because it checks `typeof === 'string'`
//   - a table name and column name containing characters that need identifier quoting
//   - a float and a negative number, to catch int-vs-float coercion
//
// Usage: bun run server-go/tools/parity/gen_store_fixtures.mjs

import { Database } from 'bun:sqlite'
import { writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { pathToFileURL } from 'node:url'
import { removeOwnFixtureOrRefuse, markAsFixture } from './fixture_guard.mjs'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')

// The TS helpers resolve nothing themselves — every probe takes an explicit path — so
// they can be imported without touching env or the runtime revision machinery.
const dbModule = await import(pathToFileURL(join(repoRoot, 'src', 'utils', 'db.ts')).href)
const { databaseHasTable, databaseHasColumns, databaseTableRowCount, databaseTableRowCountWhereEquals, databaseTextValue } =
    dbModule

const fixturesDir = join(here, 'fixtures')
mkdirSync(fixturesDir, { recursive: true })
const dbPath = join(fixturesDir, 'probe.db')
// Refuses rather than deleting anything this harness did not mark. Note this generator was
// ALREADY safe (it writes only to an explicit path it owns), and the guard is added so that
// safety is provable instead of assumed. See fixture_guard.mjs and ledger F19.
removeOwnFixtureOrRefuse(dbPath, 'gen_store_fixtures.mjs')

// ── build the probe database ────────────────────────────────────────────────
const db = new Database(dbPath, { create: true })
db.run(`
  CREATE TABLE items (
    id TEXT PRIMARY KEY,
    name TEXT,
    numeric_col INTEGER,
    null_col TEXT,
    real_col REAL,
    "odd name" TEXT
  )`)
db.run(`
  CREATE TABLE extra (
    id TEXT PRIMARY KEY,
    a TEXT,
    b TEXT,
    c TEXT
  )`)
db.run(`CREATE VIEW items_view AS SELECT id, name FROM items`)
// Stamp it as ours so a later run may delete it.
markAsFixture(db, 'gen_store_fixtures.mjs')
db.run(`CREATE TABLE "weird""table" (id TEXT PRIMARY KEY, val TEXT)`)

const insertItem = db.prepare(
    `INSERT INTO items (id, name, numeric_col, null_col, real_col, "odd name") VALUES (?, ?, ?, ?, ?, ?)`)
insertItem.run('k1', 'alpha', 42, null, 1.5, 'odd-one')
insertItem.run('k2', 'beta', 7, null, -2.25, null)
insertItem.run('k3', 'gamma', 0, null, 0.0, 'odd-three')
insertItem.run('k4', '', 1, null, 3.5, '')            // empty string value
insertItem.run('k5', 'alpha', 2, null, 4.0, 'dup')    // duplicate name for WHERE counts

// Plain db.run, NOT the items prepared statement — that one is bound to 6 parameters
// for the items table and cannot execute this insert.
db.run(`INSERT INTO "weird""table" (id, val) VALUES ('w1', 'in-weird')`)
db.close()

// ── record what the TypeScript returns ──────────────────────────────────────
const fixtures = {
    _comment:
        'GENERATED by gen_store_fixtures.mjs. Expected values come from EXECUTING the ' +
        'TypeScript against probe.db in the same directory. Do not edit by hand.',
    generatedFrom: 'src/utils/db.ts (imported)',
    dbFile: 'probe.db',
    probes: {
        hasTable: [
            { table: 'items', want: databaseHasTable(dbPath, 'items') },
            { table: 'extra', want: databaseHasTable(dbPath, 'extra') },
            // ★ A view must NOT count as a table. This is the case the previous Go
            // version got wrong.
            { table: 'items_view', want: databaseHasTable(dbPath, 'items_view') },
            { table: 'missing_table', want: databaseHasTable(dbPath, 'missing_table') },
            // Identifier quoting: the real name is  weird"table
            { table: 'weird"table', want: databaseHasTable(dbPath, 'weird"table') },
            { table: 'weirdtable', want: databaseHasTable(dbPath, 'weirdtable') },
            { table: '', want: databaseHasTable(dbPath, '') },
        ],
        hasColumns: [
            {
                table: 'items',
                columns: ['id', 'name', 'numeric_col', 'null_col', 'real_col', 'odd name'],
                want: databaseHasColumns(dbPath, 'items', ['id', 'name', 'numeric_col', 'null_col', 'real_col', 'odd name']),
            },
            {
                // A SUBSET must be true — "all present", not "exactly these".
                table: 'items',
                columns: ['id', 'name'],
                want: databaseHasColumns(dbPath, 'items', ['id', 'name']),
            },
            {
                // One missing column must make the whole answer false.
                table: 'items',
                columns: ['id', 'nope'],
                want: databaseHasColumns(dbPath, 'items', ['id', 'nope']),
            },
            {
                // Empty expectation on an existing table: vacuously true.
                table: 'items',
                columns: [],
                want: databaseHasColumns(dbPath, 'items', []),
            },
            {
                table: 'missing_table',
                columns: ['id'],
                want: databaseHasColumns(dbPath, 'missing_table', ['id']),
            },
            {
                table: 'extra',
                columns: ['a', 'b', 'c'],
                want: databaseHasColumns(dbPath, 'extra', ['a', 'b', 'c']),
            },
        ],
        rowCount: [
            { table: 'items', want: databaseTableRowCount(dbPath, 'items') },
            { table: 'extra', want: databaseTableRowCount(dbPath, 'extra') },
            { table: 'missing_table', want: databaseTableRowCount(dbPath, 'missing_table') },
            // ★ The view must NOT be readable as a table here either.
            { table: 'items_view', want: databaseTableRowCount(dbPath, 'items_view') },
            { table: 'weird"table', want: databaseTableRowCount(dbPath, 'weird"table') },
        ],
        rowCountWhereEquals: [
            { table: 'items', column: 'name', value: 'alpha', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'name', 'alpha') },
            { table: 'items', column: 'name', value: 'beta', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'name', 'beta') },
            { table: 'items', column: 'name', value: 'nope', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'name', 'nope') },
            // Empty string matches the row inserted with an empty name.
            { table: 'items', column: 'name', value: '', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'name', '') },
            // ★ INTEGER column compared against a TEXT value: pins the typing behaviour.
            { table: 'items', column: 'numeric_col', value: '42', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'numeric_col', '42') },
            { table: 'items', column: 'numeric_col', value: '0', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'numeric_col', '0') },
            { table: 'items', column: 'real_col', value: '1.5', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'real_col', '1.5') },
            { table: 'missing_table', column: 'x', value: 'y', want: databaseTableRowCountWhereEquals(dbPath, 'missing_table', 'x', 'y') },
            { table: 'items', column: 'missing_col', value: 'y', want: databaseTableRowCountWhereEquals(dbPath, 'items', 'missing_col', 'y') },
            // A value containing a quote must be bound, not interpolated.
            { table: 'items', column: 'name', value: `o'brien`, want: databaseTableRowCountWhereEquals(dbPath, 'items', 'name', `o'brien`) },
        ],
        textValue: [
            { table: 'items', keyColumn: 'id', keyValue: 'k1', valueColumn: 'name', want: databaseTextValue(dbPath, 'items', 'id', 'k1', 'name') ?? null },
            { table: 'items', keyColumn: 'id', keyValue: 'k4', valueColumn: 'name', want: databaseTextValue(dbPath, 'items', 'id', 'k4', 'name') ?? null },
            // ★ Numeric column through the text reader: TS reports undefined.
            { table: 'items', keyColumn: 'id', keyValue: 'k1', valueColumn: 'numeric_col', want: databaseTextValue(dbPath, 'items', 'id', 'k1', 'numeric_col') ?? null },
            // ★ NULL column: TS reports undefined.
            { table: 'items', keyColumn: 'id', keyValue: 'k1', valueColumn: 'null_col', want: databaseTextValue(dbPath, 'items', 'id', 'k1', 'null_col') ?? null },
            { table: 'items', keyColumn: 'id', keyValue: 'k1', valueColumn: 'real_col', want: databaseTextValue(dbPath, 'items', 'id', 'k1', 'real_col') ?? null },
            // Missing key.
            { table: 'items', keyColumn: 'id', keyValue: 'nope', valueColumn: 'name', want: databaseTextValue(dbPath, 'items', 'id', 'nope', 'name') ?? null },
            // Column with a space in its name, requiring quoting.
            { table: 'items', keyColumn: 'id', keyValue: 'k1', valueColumn: 'odd name', want: databaseTextValue(dbPath, 'items', 'id', 'k1', 'odd name') ?? null },
            { table: 'items', keyColumn: 'id', keyValue: 'k2', valueColumn: 'odd name', want: databaseTextValue(dbPath, 'items', 'id', 'k2', 'odd name') ?? null },
            { table: 'missing_table', keyColumn: 'id', keyValue: 'k1', valueColumn: 'name', want: databaseTextValue(dbPath, 'missing_table', 'id', 'k1', 'name') ?? null },
            { table: 'weird"table', keyColumn: 'id', keyValue: 'w1', valueColumn: 'val', want: databaseTextValue(dbPath, 'weird"table', 'id', 'w1', 'val') ?? null },
        ],
    },
}

writeFileSync(join(here, 'store_fixtures.json'), JSON.stringify(fixtures, null, 2) + '\n', 'utf8')

const p = fixtures.probes
console.log('wrote store_fixtures.json + fixtures/probe.db')
console.log(`  hasTable             : ${p.hasTable.length} probes`)
console.log(`  hasColumns           : ${p.hasColumns.length} probes`)
console.log(`  rowCount             : ${p.rowCount.length} probes`)
console.log(`  rowCountWhereEquals  : ${p.rowCountWhereEquals.length} probes`)
console.log(`  textValue            : ${p.textValue.length} probes`)
console.log()
console.log('  ★ the view case (hasTable must be FALSE for a view):')
const viewProbe = p.hasTable.find((x) => x.table === 'items_view')
console.log(`      hasTable("items_view") = ${viewProbe.want}`)
console.log('  ★ textValue on a numeric column (must be null = undefined):')
const numProbe = p.textValue.find((x) => x.valueColumn === 'numeric_col')
console.log(`      textValue(k1, numeric_col) = ${JSON.stringify(numProbe.want)}`)
