// Parity fixture generator for src/utils/env.ts.
//
// Unlike the other units, these functions are NOT extracted by brace-matching — the
// module is IMPORTED as a whole. Reason: getGamePaths() closes over the module-level
// `gamesDistPath`, which is derived from `root`, so pulling the function out of its
// module would change its behaviour. Importing the real module is the faithful thing.
//
// One consequence worth stating: the TypeScript derives `root` from its own SOURCE
// LOCATION (join(import.meta.dir, '../../')), which for src/utils/env.ts is the repo
// root. The Go port cannot do that — it is a standalone binary with no source — so it
// resolves root from BLORE_ROOT / the executable path instead. That is a deliberate,
// documented divergence, and it means these fixtures are comparable only when the Go
// side is given the SAME root. The Go test sets BLORE_ROOT to the repo root, so the
// paths must come out byte-identical. Anything else is a real divergence.
//
// Usage: bun run server-go/tools/parity/gen_env_fixtures.mjs

import { writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')
const envPath = join(repoRoot, 'src', 'utils', 'env.ts')

const env = await import(pathToFileURL(envPath).href)
const { normalizeGameId, getGamePaths, DEFAULT_GAME_ID, root } = env

// ── normalizeGameId ──────────────────────────────────────────────────────────
// undefined and null are distinguished because the TypeScript declares
// `gameId?: string` and uses optional chaining; JSON cannot carry undefined, so the
// tag carries it and the Go side rebuilds the same call.
const normalizeCases = [
    { tag: 'undefined', value: undefined },
    { tag: 'string', value: '' },
    { tag: 'string', value: '   ' },
    { tag: 'string', value: '\t\n ' },
    { tag: 'string', value: 'bannerlord' },
    { tag: 'string', value: 'BANNERLORD' },
    { tag: 'string', value: 'BannerLord' },
    { tag: 'string', value: '  BANNERLORD  ' },
    { tag: 'string', value: 'bannerlord ' },
    { tag: 'string', value: 'other-game' },
    { tag: 'string', value: 'OTHER-Game' },
    { tag: 'string', value: '  other  ' },
    // Non-ASCII: toLowerCase() and strings.ToLower both do Unicode simple case
    // folding, but they must be checked rather than assumed.
    { tag: 'string', value: 'ÜNÏCÖDÉ' },
    { tag: 'string', value: '中文' },
    { tag: 'string', value: 'İSTANBUL' },   // dotted capital I: a classic case-folding trap
    { tag: 'string', value: 'ΣΊΣΥΦΟΣ' },    // Greek final sigma
    { tag: 'string', value: 'ß' },          // sharp s (lowercase already)
    { tag: 'string', value: '\u00a0X\u00a0' }, // NBSP: JS trim vs Go TrimSpace again
    { tag: 'string', value: '\ufeffX' },    // BOM: the same trap the report unit hit
]

const normalizedOut = normalizeCases.map((c) => {
    let out
    try {
        out = { ok: true, result: normalizeGameId(c.value) }
    } catch (error) {
        out = { ok: false, error: String(error && error.message) }
    }
    const echoed = c.tag === 'undefined' ? null : c.value
    return { tag: c.tag, value: echoed, ...out }
})

// ── getGamePaths ─────────────────────────────────────────────────────────────
// Every field the TypeScript returns is captured, including the two the Go port
// currently omits — that omission is exactly what this fixture set is meant to expose.
const gameIds = ['bannerlord', 'BANNERLORD', '  bannerlord  ', 'other-game', '', 'ÜNÏCÖDÉ', '中文']

const pathsOut = gameIds.map((id) => {
    const paths = getGamePaths(id)
    // Record the KEYS too, not just the values: a port that silently drops a field
    // would otherwise pass a value-only comparison.
    return {
        input: id === '' ? '' : id,
        keys: Object.keys(paths).sort(),
        paths: Object.fromEntries(Object.entries(paths).sort(([a], [b]) => a.localeCompare(b))),
    }
})

const fixtures = {
    _comment:
        'GENERATED by server-go/tools/parity/gen_env_fixtures.mjs by importing ' +
        'src/utils/env.ts. Do not edit by hand.',
    generatedFrom: 'src/utils/env.ts (imported as a module, not extracted)',
    tsRoot: root,
    defaultGameId: DEFAULT_GAME_ID,
    normalize: normalizedOut,
    paths: pathsOut,
    // The Go port resolves root differently (standalone binary, no source location).
    // Recorded so the test can state the comparison precondition explicitly.
    rootNote:
        'TS root = join(import.meta.dir, "../../") = the repo root. The Go test must set ' +
        'BLORE_ROOT to that same directory or the paths are not comparable.',
}

mkdirSync(here, { recursive: true })
writeFileSync(join(here, 'env_fixtures.json'), JSON.stringify(fixtures, null, 2) + '\n', 'utf8')

console.log('wrote env_fixtures.json')
console.log(`  tsRoot          : ${root}`)
console.log(`  defaultGameId   : ${DEFAULT_GAME_ID}`)
console.log(`  normalize cases : ${normalizedOut.length}`)
console.log(`  getGamePaths    : ${pathsOut.length} ids, ${pathsOut[0].keys.length} fields each`)
console.log()
console.log('  fields the TypeScript returns:')
for (const k of pathsOut[0].keys) console.log(`      ${k}`)
console.log()
console.log('  normalizeGameId results:')
for (const c of normalizedOut) {
    console.log(`      ${String(c.tag).padEnd(10)} ${JSON.stringify(c.value).padEnd(14)} -> ${c.ok ? JSON.stringify(c.result) : 'THREW'}`)
}
