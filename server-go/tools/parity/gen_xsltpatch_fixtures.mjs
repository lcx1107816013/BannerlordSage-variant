// Parity fixture generator for generate_xslt_patch
//   src/tools/generate-xslt-patch.ts -> tools.GenerateXsltPatch
//
// Expected values come from EXECUTING the real TypeScript — the tool returns a plain stylesheet
// string (no report wrapper), so the fixture captures that text exactly.
//
// The corpus targets the details a careful reader would "fix" in a port:
//   - `fragment?.trim() || '...'` is a truthiness test on the TRIMMED value, so "   " uses the
//     placeholder and a fragment wrapped in newlines loses them
//   - the operation is compared as an exact string; an UNKNOWN operation falls through to the
//     INSERT branch rather than erroring
//   - indentFragment splits on /\r?\n/ — CRLF is ONE separator, a LONE CR is NONE — and always
//     rejoins with "\n"
//   - the `delete` template is self-closing with an EMPTY body (that is what makes it a delete)
//   - the interpolated operation text already ends in a newline, and the template adds another
//     before </xsl:stylesheet>
//
// Usage: bun run server-go/tools/parity/gen_xsltpatch_fixtures.mjs

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')

const mod = await import(pathToFileURL(join(repoRoot, 'src', 'tools', 'generate-xslt-patch.ts')).href)
const { generateXsltPatch } = mod

const cases = [
  // basic shapes
  { xpath: '/ModuleData/Items/Item[@id="x"]', op: 'insert', fragment: '<Item id="y" />' },
  { xpath: '/ModuleData/Items/Item[@id="x"]', op: 'replace', fragment: '<Item id="y" />' },
  { xpath: '/ModuleData/Items/Item[@id="x"]', op: 'delete' },
  // fragment handling: absent, empty, whitespace-only, multi-line, CRLF, lone CR, trailing newline
  { xpath: '//a', op: 'insert' },
  { xpath: '//a', op: 'insert', fragment: '' },
  { xpath: '//a', op: 'insert', fragment: '   ' },
  { xpath: '//a', op: 'insert', fragment: '\n\n' },
  { xpath: '//a', op: 'insert', fragment: 'one\ntwo\nthree' },
  { xpath: '//a', op: 'insert', fragment: 'one\r\ntwo' },
  { xpath: '//a', op: 'insert', fragment: 'one\rtwo' },
  { xpath: '//a', op: 'insert', fragment: 'trailing\n' },
  { xpath: '//a', op: 'insert', fragment: '  padded  ' },
  { xpath: '//a', op: 'replace', fragment: 'one\ntwo' },
  { xpath: '//a', op: 'replace', fragment: '   ' },
  // delete ignores the fragment entirely
  { xpath: '//a', op: 'delete', fragment: '<ignored />' },
  // an UNKNOWN operation must take the insert branch, not error
  { xpath: '//a', op: 'upsert', fragment: '<z />' },
  // xpath text is interpolated raw — braces/quotes must survive
  { xpath: '//a[@b="c"][d>1]', op: 'insert', fragment: '<x/>' },
  { xpath: '', op: 'insert', fragment: '<x/>' },
  // a fragment that itself contains an xsl:template, to be sure nothing is escaped
  { xpath: '//a', op: 'insert', fragment: '<xsl:template match="x"><y/></xsl:template>' },
]

const out = []
for (const c of cases) {
  let entry
  try {
    const res = await generateXsltPatch(c.xpath, c.op, c.fragment)
    entry = { ...c, ok: true, text: res.content[0].text }
  } catch (error) {
    entry = { ...c, ok: false, error: String(error?.message ?? error) }
  }
  out.push(entry)
}

const fixtures = {
  _comment:
    'GENERATED by gen_xsltpatch_fixtures.mjs. Expected values come from EXECUTING the real ' +
    'src/tools/generate-xslt-patch.ts. Do not edit by hand.',
  cases: out,
}
writeFileSync(join(here, 'xsltpatch_fixtures.json'), JSON.stringify(fixtures, null, 2) + '\n', 'utf8')

console.log('wrote xsltpatch_fixtures.json')
console.log(`  cases: ${out.length} (${out.filter(c => c.ok).length} rendered)`)
console.log()
console.log('  ★ the delete branch (empty template body):')
const del = out.find(c => c.op === 'delete')
if (del) console.log(JSON.stringify(del.text.split('\n').slice(-6).join('\n')))
console.log()
console.log('  ★ an unknown operation fell through to insert:')
const unk = out.find(c => c.op === 'upsert')
if (unk) console.log(unk.text.includes('Insert content inside the target node') ? '      yes' : '      NO — investigate')
