// Parity fixture generator for src/utils/tool-naming.ts
//   archiveToolName / archiveTool
//
// Both exports are public, so they are imported and executed directly — no extraction needed.
//
// Usage: bun run server-go/tools/parity/gen_toolnaming_fixtures.mjs

import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..', '..')
const NL = String.fromCharCode(10)

const mod = await import(pathToFileURL(join(repoRoot, 'src', 'utils', 'tool-naming.ts')).href)

// The corpus separates the rules: stripping only at the start, stripping only the FIRST match,
// re-applying to an already-prefixed name, and the non-ASCII / empty edges.
const names = [
  'bannerlord_doctor',
  'get_clan_summary',
  'bannerlord_',
  'bannerlord',
  'BANNERLORD_doctor',
  'bannerlord_bannerlord_doctor',
  'x_bannerlord_y',
  'bannerlord',
  '',
  'ba_doctor',
  'ba_ba_doctor',
  'bannerlord.get_clan',
  '_bannerlord_x',
  'bannerlord_中文',
]

const cases = names.map(legacyName => {
  const name = mod.archiveToolName(legacyName)
  const pair = mod.archiveTool(legacyName)
  return { legacyName, name, pairName: pair.name, pairLegacy: pair.legacy }
})

const fixtures = {
  _comment:
    'GENERATED by gen_toolnaming_fixtures.mjs. Expected values come from EXECUTING the real ' +
    'src/utils/tool-naming.ts. Do not edit by hand.',
  archivePrefix: mod.ARCHIVE_PREFIX,
  cases,
}
writeFileSync(join(here, 'toolnaming_fixtures.json'), JSON.stringify(fixtures, null, 2) + NL, 'utf8')

console.log('wrote toolnaming_fixtures.json')
console.log('  cases: ' + cases.length)
console.log('')
console.log('  ★ the boundary cases a "tidy" implementation gets wrong:')
for (const n of ['x_bannerlord_y', 'bannerlord_bannerlord_doctor', 'ba_doctor', 'bannerlord_']) {
  const c = cases.find(x => x.legacyName === n)
  console.log('      ' + JSON.stringify(n).padEnd(32) + ' -> ' + JSON.stringify(c.name))
}
